import { chromium } from "playwright";
const URL_ = "https://mellizo.vercel.app";
const ctx = await chromium.launchPersistentContext("/tmp/mellizo-video-profile", { viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
await p.goto(URL_, { waitUntil: "networkidle" });
await p.waitForTimeout(1800);
await p.screenshot({ path: "docs/entry-desktop.png" });
await p.getByRole("button", { name: /hang one of ours/i }).click();
await p.waitForSelector(".phase-result", { timeout: 120000 });
await p.waitForTimeout(4200);
await p.screenshot({ path: "docs/result-desktop.png" });
await p.getByRole("button", { name: "near misses" }).click();
await p.waitForTimeout(1600);
await p.screenshot({ path: "docs/misses-desktop.png" });
const ctx2 = await chromium.launchPersistentContext("/tmp/mellizo-video-profile2", { viewport: { width: 390, height: 844 } });
const m = await ctx2.newPage();
await m.goto(URL_, { waitUntil: "networkidle" });
await m.waitForTimeout(1500);
await m.screenshot({ path: "docs/entry-mobile.png" });
await m.getByRole("button", { name: /hang one of ours/i }).click();
await m.waitForSelector(".phase-result", { timeout: 120000 });
await m.waitForTimeout(4200);
await m.screenshot({ path: "docs/result-mobile.png" });
await m.getByRole("button", { name: "near misses" }).click();
await m.waitForTimeout(1600);
await m.screenshot({ path: "docs/misses-mobile.png" });
await ctx.close(); await ctx2.close();
console.log("done");
